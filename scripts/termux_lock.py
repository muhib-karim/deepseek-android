#!/usr/bin/env python3
"""Write engine/termux-packages.lock: the Termux .deb packages the engine payload is built from, pinned with sha256.

Run by hand (or from a workflow) only to refresh the pins; scripts/build-dsh-payload.sh never resolves anything itself,
it downloads exactly the files listed in the lock and checks each sha256. Termux keeps only current builds on its
mirror, so a pin can disappear: CI then fails at download with the package name, and this script refreshes the lock.

usage: python3 -I scripts/termux_lock.py [--packages-dir DIR]   (DIR holds Packages-aarch64 / Packages-x86_64; else fetched)
"""
import argparse
import os
import re
import sys
import urllib.request

REPO = "https://packages.termux.dev/apt/termux-main"
ARCHES = ("aarch64", "x86_64")
# What the harness runs: node (LTS), bash, ripgrep, GNU coreutils, git (plugin installs from git URLs), TLS roots.
ROOTS = ("nodejs-lts", "bash", "ripgrep", "coreutils", "git", "ca-certificates", "openssl")
# Termux's own helper scripts and git's pager are not needed inside the app (GIT_PAGER=cat).
SKIP = {"termux-tools", "termux-am", "termux-exec", "less", "dash", "termux-keyring", "termux-licenses"}
LOCK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "termux-packages.lock")


def parse_index(text):
    packages = {}
    for block in text.split("\n\n"):
        fields = {}
        for line in block.splitlines():
            if ":" in line and not line.startswith(" "):
                key, value = line.split(":", 1)
                fields[key] = value.strip()
        if "Package" in fields:
            packages[fields["Package"]] = fields
    return packages


def depends(fields):
    out = []
    for clause in (fields.get("Pre-Depends", "") + "," + fields.get("Depends", "")).split(","):
        clause = clause.strip()
        if clause:
            out.append(re.split(r"[\s(]", clause.split("|")[0].strip())[0])
    return out


def resolve(packages, roots):
    seen, order = set(), []
    stack = list(roots)
    while stack:
        name = stack.pop(0)
        if name in seen or name in SKIP:
            continue
        if name not in packages:
            raise SystemExit(f"package not in the index: {name}")
        seen.add(name)
        order.append(name)
        stack.extend(depends(packages[name]))
    return sorted(order)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--packages-dir")
    args = parser.parse_args()
    lines = ["# Generated by scripts/termux_lock.py; consumed by scripts/build-dsh-payload.sh. Do not edit by hand.",
             f"# Source: {REPO} (Termux packages; licences and corresponding source: THIRD-PARTY.md).",
             "# arch package version filename sha256 size"]
    for arch in ARCHES:
        if args.packages_dir:
            with open(os.path.join(args.packages_dir, f"Packages-{arch}"), encoding="utf-8") as fh:
                text = fh.read()
        else:
            with urllib.request.urlopen(f"{REPO}/dists/stable/main/binary-{arch}/Packages", timeout=60) as response:
                text = response.read().decode("utf-8")
        packages = parse_index(text)
        for name in resolve(packages, ROOTS):
            p = packages[name]
            lines.append(" ".join((arch, name, p["Version"], p["Filename"], p["SHA256"], p["Size"])))
    with open(LOCK, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {LOCK}: {len(lines) - 3} packages", file=sys.stderr)


if __name__ == "__main__":
    main()
